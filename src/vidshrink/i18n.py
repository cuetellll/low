def set_lang(lang: str) -> None:
    global LANG
    LANG = lang if lang in STR else "en"


def tr(key: str, **kw) -> str:
    text = STR.get(LANG, {}).get(key) or STR["en"].get(key) or key
    return text.format(**kw) if kw else text
